import { PdfDocumentSchema, type PdfDocument } from '@mn/contracts';
import { parseMathLatex, printSegmentLatex, validateExpr } from '@mn/contracts/ir';
import { safeRawMath } from './raw-math';

/** Only text is escaped; math is parsed and reprinted through the shared IR, or rebuilt from allowed tokens. */
export function escapeTex(text: string): string {
  const escapes: Record<string, string> = { '\\': '\\textbackslash{}', '{': '\\{', '}': '\\}', '$': '\\$', '&': '\\&', '#': '\\#', '%': '\\%', '_': '\\_', '^': '\\textasciicircum{}', '~': '\\textasciitilde{}' };
  return text.replace(/[\\{}$&#%_^~]/g, c => escapes[c]!).replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f\u007f]/g, '').replace(/\r\n?/g, '\n');
}

function mathTex(value: string): string {
  const parsed = parseMathLatex(value);
  if (parsed.ok && !validateExpr(parsed.expr)) return printSegmentLatex(parsed.expr, parsed.notation);
  // notation outside the IR (\min, \forall, …) typesets only if every token is on the allow-list
  const raw = safeRawMath(value);
  if (raw === null) throw new Error('IR_INVALID');
  return raw;
}

/** A fixed, self-contained adaptation of homework_example.tex; sample answers are excluded. */
export function serializeLatex(value: PdfDocument): string {
  const data = PdfDocumentSchema.parse(value);
  const h = data.homework ?? { course: '', institution: '', date: '', exercise: '1', paper: 'letter', include_records: true };
  const ja = data.language === 'ja';
  const out = [
    '% Generated by Math Notebook. Compile with LuaLaTeX.',
    '\\documentclass[10pt]{article}',
    '\\usepackage{amsmath,amssymb,mathtools,geometry,fancyhdr,graphicx}',
    '\\usepackage[haranoaji]{luatexja-preset}',
    '\\setmainfont{Latin Modern Roman}',
    '\\geometry{' + (h.paper === 'a4' ? 'a4paper' : 'letterpaper') + ',top=20mm,bottom=30mm,left=26mm,right=30mm}',
    '\\setlength{\\parindent}{0pt}',
    '\\setlength{\\parskip}{0.45em}',
    '\\allowdisplaybreaks',
    '\\pagestyle{fancy}\\fancyhf{}\\renewcommand{\\headrulewidth}{0pt}',
    '\\fancyfoot[C]{- \\thepage \\, -}',
    '\\setlength{\\headheight}{14pt}',
    '\\newsavebox{\\ReportMathBox}',
    '\\newcommand{\\ReportEquation}[1]{\\begingroup\\sbox{\\ReportMathBox}{$\\displaystyle #1$}\\[\\ifdim\\wd\\ReportMathBox>\\linewidth\\resizebox{\\linewidth}{!}{\\usebox{\\ReportMathBox}}\\else\\usebox{\\ReportMathBox}\\fi\\]\\endgroup}',
    '\\begin{document}',
    '\\noindent\\begin{minipage}[t]{0.49\\linewidth}\\raggedright',
    '\\textbf{' + escapeTex(h.course) + '}\\par ' + escapeTex(h.institution),
    '\\end{minipage}\\hfill\\begin{minipage}[t]{0.49\\linewidth}\\raggedleft',
    '\\textbf{' + escapeTex(data.author ?? '') + '}\\par ' + escapeTex(data.student_id ?? '') + '\\par ' + escapeTex(h.date),
    '\\end{minipage}',
    '\\begin{center}\\large\\bfseries ' + escapeTex(data.title) + '\\end{center}',
    '\\hrule height 1pt\\vspace{1em}',
    '\\textbf{' + (ja ? '設問 ' : 'Exercise ') + escapeTex(h.exercise || '1') + '.}\\par',
  ];
  const records: string[] = [];
  for (const section of data.sections) {
    const historical = section.title === 'Revision history' || section.title === '修正履歴';
    if (historical) { if (h.include_records) records.push('\\subsection*{' + escapeTex(section.title) + '}'); }
    else out.push('\\subsection*{' + escapeTex(section.title) + '}');
    for (const block of section.blocks) {
      const body: string[] = [];
      const mixed = block.fragments.some(f => f.kind === 'text') && block.fragments.some(f => f.kind === 'math');
      // two formulas side by side get a space: "$a$$b$" would open display math
      if (mixed) body.push(block.fragments.map((f, i) => f.kind === 'text' ? escapeTex(f.value) : (block.fragments[i - 1]?.kind === 'math' ? ' $' : '$') + mathTex(f.value) + '$').join('') + '\\par');
      else for (const f of block.fragments) body.push(f.kind === 'text' ? escapeTex(f.value) + '\\par' : '\\ReportEquation{' + mathTex(f.value) + '}');
      if (!historical) out.push(...body);
      if (h.include_records && (block.notes.length || historical)) {
        records.push('\\textbf{' + (ja ? '行 ' : 'Line ') + escapeTex(block.label) + '}\\par', ...body,
          ...block.notes.map(n => '{\\small ' + escapeTex(n) + '}\\par'), '\\medskip');
      }
    }
  }
  if (records.length) out.push('\\clearpage', '\\section*{' + (ja ? '検証記録・修正履歴' : 'Verification and revision record') + '}', ...records);
  out.push('\\end{document}', '');
  const tex = out.join('\n');
  if (new TextEncoder().encode(tex).length > 1024 * 1024) throw new Error('EXPORT_TOO_LARGE');
  return tex;
}
