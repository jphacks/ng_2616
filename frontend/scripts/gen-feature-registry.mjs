// Generates src/features/registry.generated.ts importing only enabled Should/Could features
// (spec §2.3): the Must-only build has an empty registry, so absent optional packages are never
// resolved by the bundler.
import { existsSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const known = ['hints', 'assist_modes', 'bridge', 'plot', 'lean', 'autosave', 'auto_submit', 'resources'];
const enabled = (process.env.NEXT_PUBLIC_ENABLED_FEATURES ?? '')
  .split(',')
  .map((s) => s.trim())
  .filter(Boolean);
for (const f of enabled) if (!known.includes(f)) throw new Error(`unknown feature "${f}"`);

const lines = ['// generated by scripts/gen-feature-registry.mjs; do not edit', "import type { FeaturePlugin } from './types';", ''];
const names = [];
for (const f of enabled) {
  const dir = f.replace('_', '-');
  if (!existsSync(join(here, '..', 'src', 'features', dir, 'index.ts'))) {
    console.warn(`feature "${f}" enabled but src/features/${dir} does not exist yet; skipped`);
    continue;
  }
  const ident = f.replace(/_(\w)/g, (_, c) => c.toUpperCase());
  lines.push(`import ${ident} from './${dir}';`);
  names.push(ident);
}
lines.push('', `export const FEATURES: FeaturePlugin[] = [${names.join(', ')}];`, '');
writeFileSync(join(here, '..', 'src', 'features', 'registry.generated.ts'), lines.join('\n'));
console.log(`feature registry: [${names.join(', ')}]`);
